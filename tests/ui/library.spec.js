import { test, expect } from '@playwright/test'

// Each test gets a fresh browser context, separate from the user's library.
test('library navigation, shadcn controls, search, sorting and playback', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await expect(page.locator('.album-card')).toHaveCount(6)
  await expect(page.locator('.album-card').first()).toHaveAttribute('data-slot', 'card')
  await expect(page.getByRole('button', { name: 'New album', exact: true }).first()).toHaveAttribute('data-slot', 'button')
  await expect(page.locator('body')).not.toContainText('Local workspace')
  await page.getByRole('searchbox').fill('blue')
  await expect(page.locator('.album-card')).toHaveCount(1)
  await page.getByRole('searchbox').fill('')
  await page.getByLabel('Sort', { exact: true }).selectOption('name')
  await expect(page.locator('.album-title').first()).toHaveText('After hours')
  await page.getByRole('button', { name: 'List view', exact: true }).click()
  await expect(page.locator('.album-list')).toBeVisible()
  await page.getByRole('button', { name: 'Grid view', exact: true }).click()
  await page.screenshot({ path: '/tmp/still-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Open Blue hour', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Blue hour', exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/still-project.png', fullPage: true })
  await expect(page.locator('.track-table tbody tr')).toHaveCount(4)
  await page.getByRole('button', { name: 'Play album', exact: true }).click()
  await expect(page.locator('#play-pause')).toHaveAttribute('aria-label', 'Pause')
  await expect(page.locator('#player-title')).toHaveText('the way home')
  await page.locator('#next').click()
  await expect(page.locator('#player-title')).toHaveText('somewhere, slowly')
  await page.getByRole('button', { name: 'All tracks', exact: true }).click()
  await expect(page.locator('.track-table tbody tr')).toHaveCount(15)
  await expect(page.locator('#play-pause')).toHaveAttribute('aria-label', 'Pause')
  await page.locator('#play-pause').click()
  await page.getByRole('button', { name: 'Favorites', exact: true }).click()
  await expect(page.locator('.album-card')).toHaveCount(1)
  await expect(page.locator('.album-title')).toHaveText('Blue hour')
  expect(errors).toEqual([])
})

test('create and edit album, upload audio, save notes, reload and export', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'New album', exact: true }).first().click()
  await page.getByLabel('Album name', { exact: true }).fill('Test album')
  await page.getByLabel('Description', { exact: true }).fill('Session notes')
  await page.getByLabel('Status', { exact: true }).selectOption('Ready')
  await page.getByRole('button', { name: 'Create album', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Test album', exact: true })).toBeVisible()
  await expect(page.locator('.status-pill')).toHaveText('Ready')
  await page.getByRole('button', { name: 'Edit album', exact: true }).click()
  await expect(page.getByLabel('Status', { exact: true })).toHaveValue('Ready')
  await page.getByLabel('Album name', { exact: true }).fill('Updated album')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Updated album', exact: true })).toBeVisible()
  await page.getByLabel('Album notes', { exact: true }).fill('Saved note')
  await expect(page.locator('#note-save-status')).toHaveText('Saved')
  // A real one-second silent WAV checks the existing file and playback path.
  const wav = Buffer.alloc(44 + 22050 * 2)
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8)
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22)
  wav.writeUInt32LE(22050, 24); wav.writeUInt32LE(44100, 28); wav.writeUInt16LE(2, 32)
  wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(44100, 40)
  await page.getByRole('button', { name: 'Add tracks', exact: true }).click()
  const chooserPromise = page.waitForEvent('filechooser')
  await page.locator('#browse-audio').click()
  const chooser = await chooserPromise
  await chooser.setFiles({ name: 'test-recording.wav', mimeType: 'audio/wav', buffer: wav })
  await expect(page.locator('.track-name')).toHaveText('test-recording')
  await page.reload()
  await expect(page.locator('.track-name')).toHaveText('test-recording')
  await expect(page.getByLabel('Album notes', { exact: true })).toHaveValue('Saved note')
  await page.getByRole('button', { name: 'Play album', exact: true }).click()
  await expect(page.locator('#player-title')).toHaveText('test-recording')
  await page.locator('#profile-top').click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^still-backup-.*\.still$/)
  expect(errors).toEqual([])
})

test('mobile navigation and layouts fit the screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('.album-card')).toHaveCount(6)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '/tmp/still-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Toggle menu', exact: true }).click()
  await expect(page.locator('.sidebar')).toHaveClass(/open/)
  await page.getByRole('button', { name: 'All tracks', exact: true }).click()
  await expect(page.locator('.sidebar')).not.toHaveClass(/open/)
  await expect(page.locator('.track-table tbody tr')).toHaveCount(15)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
